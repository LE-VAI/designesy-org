// The live score badge: "Scored by Designesy", the site, the grade, the score
// and the date the score was measured, drawn as one SVG.
//
// The embed is a per-site badge carrying the real
// grade, worded "Scored by Designesy". The static images it replaces as the
// lead embed read "Verified by Designesy" for every site, F included; a seal
// that reads the same whatever the finding does not reflect the finding.
//
// This module only draws. The route (live-badge-route.ts) decides what to draw
// from the score cache; this file has no network, no cache and no clock.
//
// TYPE
// An <img> cannot load web fonts, so the text is outlined from the site's own
// faces (glyphs.ts, generated by scripts/build-badge-glyphs.py): the same type
// on every machine, and an exact width to lay out against. The words still
// reach assistive technology through the SVG's <title> and aria-label.
//
// LAYOUT (44 px tall, outer radius 8, width from the content)
//   [mark]  SCORED BY DESIGNESY           primer.style
//           A 90.4 /100                     2026-10-11
// Sizes: label 10 px Schibsted 700 at
// 0.08em, site and date 10 px Atkinson Hyperlegible Mono (it replaced
// Geist Mono, 0.632em a character against 0.6em, so a 26-character host is
// 8.3 px wider), the reading 16 px. 10 px is the
// smallest text on the badge, an exception to the site's 12.8px text floor for
// a fixed-height graphic embedded at 1x in READMEs.
// The reading follows the result page's readout: the grade letter and the
// score in one face, the letter in its grade's text colour, no box around it,
// "/100" small in the mono. The face is Schibsted Grotesk 700, the site's UI
// face, rather than the readout's Fraunces: at 15 px the display cut's 4 read
// as an A (rendered at 1x, 2026-10-11).
//
// The static images public/badge.svg and public/badge-light.svg come from
// renderStaticBadge below (scripts/badge-renders.mjs writes them): the
// same outlined label and mark, so the static and live badges set the words
// alike on every machine. public/badge-compact.svg is the mark alone.
//
// COLOUR
// The badge carries its own ground, so it does not depend on the host page's
// theme. Dark ground is the site's dark --paper, light ground its light
// --surface, and every colour on them is that theme's own token: --ink for the
// score, --muted for the label, site, date and /100, and the grade's
// --grade-<g>-ink for the letter (a grade takes only its grade tokens).
// scripts/check-badge-grade-tokens.js ties each literal below to
// globals.css and measures every text colour against its ground (4.5:1).

import { BODY, LABEL, MONO, type BadgeFace } from './glyphs';
import { MARK_ART, markSvg } from './mark';
import { fmtScore } from '../../score/verdict';

export type BadgeTheme = 'dark' | 'light';

export type LiveBadgeState =
  /** A score from the cache: the grade, the score and the UTC date of the run. */
  | { kind: 'scored'; grade: string; score: number; date: string; host: string }
  /** No score to show: the URL is missing or blocked, or the site could not be read. */
  | { kind: 'not-scored'; host: string | null };

/** The ground and its text colours, per theme (globals.css :root and [data-theme="light"]). */
export const BADGE_GROUND: Record<BadgeTheme, { ground: string; rim: string; ink: string; muted: string; body: '#FFFFFF' | '#010102' }> = {
  // --paper #010102; --ink #f5f5f7; --muted #a0a0a0. The rim is the static
  // badge's (public/badge.svg).
  dark: { ground: '#010102', rim: 'rgba(255,255,255,0.12)', ink: '#f5f5f7', muted: '#a0a0a0', body: '#FFFFFF' },
  // --surface #ffffff; --ink #1a1a1e; --muted #555560. Rim as public/badge-light.svg.
  light: { ground: '#ffffff', rim: 'rgba(0,0,0,0.12)', ink: '#1a1a1e', muted: '#555560', body: '#010102' },
};

/**
 * The grade letter's colour: the theme's --grade-<g>-ink, the grade's text
 * token. Dark -ink equals the dark base; light -ink is the darker text step.
 */
export const GRADE_INK: Record<BadgeTheme, Record<string, string>> = {
  dark: {
    A: '#22c55e',
    B: '#84cc16',
    C: '#eab308',
    D: '#fb7185',
    F: '#ef4444',
  },
  light: {
    A: '#147839',
    B: '#497509',
    C: '#896203',
    D: '#be1f67',
    F: '#cd2323',
  },
};

// ── Type metrics (px at 1x) ──────────────────────────────────────────────────
const H = 44;
const PAD_X = 12;
const LABEL_SIZE = 10;
const LABEL_TRACK = 0.08; // em
const READ_SIZE = 16;
const MONO_SIZE = 10;
const BODY_SIZE = 15;
const ROW1 = 18; // baseline of the label and the site
const ROW2 = 34; // baseline of the reading and the date
const MARK_GAP = 9; // mark art to text
const COL_GAP = 20; // label column to site/date column
const OUT_OF_GAP = 4; // score to "/100"
const HOST_MAX = 26; // characters, then an ellipsis

type Run = {
  width: number;
  /** The run as one filled <path>, its origin at (x, baseline). */
  draw: (x: number, baseline: number, fill: string) => string;
};

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

/**
 * Lays a string out in a face. The path stays in integer font units; one
 * transform scales it to `size` and flips y. Each glyph is placed by
 * rewriting its leading absolute M (glyphs.ts keeps every later command
 * relative), so the output is short.
 */
function run(face: BadgeFace, text: string, size: number, trackEm = 0): Run {
  const k = size / face.upm;
  const track = trackEm * face.upm;
  const chars = [...text];
  let d = '';
  let x = 0;
  chars.forEach((ch, i) => {
    const g = face.glyphs[ch];
    if (!g) throw new Error(`badge glyphs: no "${ch}" in this face`);
    const at = Math.round(x);
    d += g.d.replace(/^M(-?\d+) /, (_, gx: string) => `M${Number(gx) + at} `);
    x += g.w;
    const next = chars[i + 1];
    if (next !== undefined) x += (face.kern[ch + next] ?? 0) + track;
  });
  return {
    width: x * k,
    draw(ox, baseline, fill) {
      const s = Math.round(k * 1e6) / 1e6;
      return `<path fill="${fill}" transform="matrix(${s} 0 0 ${-s} ${round2(ox)} ${round2(baseline)})" d="${d}"/>`;
    },
  };
}

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/** The host as the badge shows it: lower case, no "www.", at most HOST_MAX characters. */
export function displayHost(host: string): string {
  const h = host.toLowerCase().replace(/^www\./, '').replace(/[^a-z0-9.-]/g, '');
  return h.length > HOST_MAX ? h.slice(0, HOST_MAX - 1) + '…' : h;
}

/** The sentence the badge says, in reading order: "Scored by Designesy: B, 84.6, 2026-10-11, vercel.com". */
export function badgeLabel(state: LiveBadgeState): string {
  if (state.kind === 'scored') {
    return `Scored by Designesy: ${state.grade}, ${fmtScore(state.score)}, ${state.date}, ${displayHost(state.host)}`;
  }
  return state.host ? `Designesy score: not scored, ${displayHost(state.host)}` : 'Designesy score: not scored';
}

/** The badge as an SVG document. */
export function renderLiveBadge(state: LiveBadgeState, theme: BadgeTheme = 'dark'): string {
  const c = BADGE_GROUND[theme];
  const host = state.host ? displayHost(state.host) : '';

  // The mark's art spans the label's cap top to the reading's baseline.
  const capTop = ROW1 - (LABEL.capHeight / LABEL.upm) * LABEL_SIZE;
  const artH = ROW2 - capTop;
  const markSize = (artH * MARK_ART.box) / (MARK_ART.bottom - MARK_ART.top);
  const markX = PAD_X - (MARK_ART.left / MARK_ART.box) * markSize;
  const markY = capTop - (MARK_ART.top / MARK_ART.box) * markSize;
  const textX = PAD_X + ((MARK_ART.right - MARK_ART.left) / MARK_ART.box) * markSize + MARK_GAP;

  const parts: string[] = [];
  let leftW: number;
  const right: { run: Run; baseline: number }[] = [];

  if (state.kind === 'scored') {
    const label = run(LABEL, 'SCORED BY DESIGNESY', LABEL_SIZE, LABEL_TRACK);
    const letter = run(LABEL, state.grade, READ_SIZE);
    const gap = 0.28 * READ_SIZE;
    const score = run(LABEL, fmtScore(state.score), READ_SIZE);
    const outOf = run(MONO, '/100', MONO_SIZE);
    const readW = letter.width + gap + score.width + OUT_OF_GAP + outOf.width;
    leftW = Math.max(label.width, readW);

    parts.push(label.draw(textX, ROW1, c.muted));
    const gradeInk = GRADE_INK[theme][state.grade] ?? c.ink;
    parts.push(letter.draw(textX, ROW2, gradeInk));
    parts.push(score.draw(textX + letter.width + gap, ROW2, c.ink));
    parts.push(outOf.draw(textX + letter.width + gap + score.width + OUT_OF_GAP, ROW2, c.muted));
    right.push({ run: run(MONO, host, MONO_SIZE), baseline: ROW1 });
    right.push({ run: run(MONO, state.date, MONO_SIZE), baseline: ROW2 });
  } else {
    const label = run(LABEL, 'DESIGNESY SCORE', LABEL_SIZE, LABEL_TRACK);
    const line = run(BODY, 'Not scored', BODY_SIZE);
    leftW = Math.max(label.width, line.width);
    parts.push(label.draw(textX, ROW1, c.muted));
    parts.push(line.draw(textX, ROW2, c.ink));
    if (host) right.push({ run: run(MONO, host, MONO_SIZE), baseline: ROW1 });
  }

  const rightW = right.reduce((w, r) => Math.max(w, r.run.width), 0);
  const W = Math.ceil(textX + leftW + (rightW ? COL_GAP + rightW : 0) + PAD_X);
  for (const r of right) {
    parts.push(r.run.draw(W - PAD_X - r.run.width, r.baseline, c.muted));
  }

  const said = escapeXml(badgeLabel(state));
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="${said}">` +
    `<title>${said}</title>` +
    // Inset half the rim's width, so the rim is whole and the outer radius is 8.
    `<rect x="0.5" y="0.5" width="${W - 1}" height="${H - 1}" rx="7.5" fill="${c.ground}" stroke="${c.rim}"/>` +
    markSvg(round2(markX), round2(markY), round2(markSize), c.body) +
    parts.join('') +
    `</svg>`
  );
}

// ── The static images ────────────────────────────────────────────────────────
// public/badge.svg (dark ground) and public/badge-light.svg (light ground),
// 156 x 32 as they have always been, so existing embeds with width="156"
// height="32" keep their box. They read "SCORED BY DESIGNESY" and carry no
// grade. The label is the live badge's (Schibsted 700, 10 px, outlined); its
// tracking and the mark's place are set so the margin left of the mark's art
// equals the margin right of the label.

const STATIC_W = 156;
const STATIC_H = 32;
const STATIC_MARK = 22; // px, the mark's 512 box
const STATIC_TRACK = 0.02; // em
const STATIC_GAP = 6; // mark art to label
const STATIC_BASELINE = 19.5; // centres the label's caps (7 px) in 32

/** A static image as an SVG document: `dark` is ink ground, `light` is white. */
export function renderStaticBadge(theme: BadgeTheme): string {
  const c = BADGE_GROUND[theme];
  const label = run(LABEL, 'SCORED BY DESIGNESY', LABEL_SIZE, STATIC_TRACK);
  const artW = ((MARK_ART.right - MARK_ART.left) / MARK_ART.box) * STATIC_MARK;
  const margin = (STATIC_W - artW - STATIC_GAP - label.width) / 2;
  const markX = margin - (MARK_ART.left / MARK_ART.box) * STATIC_MARK;
  const markY = (STATIC_H - STATIC_MARK) / 2;
  const text = theme === 'dark' ? '#ffffff' : '#010102';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${STATIC_W}" height="${STATIC_H}" viewBox="0 0 ${STATIC_W} ${STATIC_H}" role="img" aria-label="Scored by Designesy">
` +
    `  <title>Scored by Designesy</title>
` +
    `  <rect width="${STATIC_W}" height="${STATIC_H}" rx="6" fill="${c.ground}" stroke="${c.rim}" stroke-width="1"/>
` +
    `  ${markSvg(round2(markX), round2(markY), STATIC_MARK, c.body)}
` +
    `  ${label.draw(margin + artW + STATIC_GAP, STATIC_BASELINE, text)}
` +
    `</svg>
`
  );
}
