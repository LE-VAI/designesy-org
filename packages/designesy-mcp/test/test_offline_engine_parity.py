"""Parity gate: the Python offline engine against the live TypeScript engine.

designesy_score falls back to a Python port of the scoring engine when the
live API is unreachable. Nothing compared the two until this file, and the
port had drifted far enough that its offline scores disagreed with the site's
on the same page.

HOW IT WORKS
packages/score/scripts/export-offline-golden.mjs runs the built TypeScript
engine (the same check code as the live route; source-drift.mjs keeps the two
identical) over the calibration corpus, the recorded parity page, edge inputs
and scope auto-detection cases, under both scopes, and writes every check
result to test/fixtures/offline-engine-golden.json. This file scores the same
inputs with the Python engine and requires the same status, item, category and
detail for every check the Python engine runs.

CI runs the exporter with --check, so the golden cannot fall behind the
TypeScript engine; a change there regenerates the golden, and this file then
fails until the port follows.

NO SILENT GAPS
Checks the Python engine does not run are listed, with a reason, in
designesy_mcp_server._OFFLINE_NOT_IMPLEMENTED. The ported list and that list
must together be exactly the live engine's check list, so a check added to the
live engine fails here until it is ported or listed.

WHAT THIS DOES NOT MEASURE
The browser probes for v02 and v21 (they need the Chrome DevTools endpoint
DESIGNESY_CDP_URL names; the parity runs score with browser_probes=False and
both engines read MANUAL), the
network fetch itself (timeouts, redirects, candidate URLs), and the score: the
offline score is an unweighted pass rate over a subset and says so.
"""

from __future__ import annotations

