import designesy_mcp_server as mcp  # noqa: E402

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
GOLDEN = HERE / "fixtures" / "offline-engine-golden.json"

with GOLDEN.open(encoding="utf-8") as _f:
    G = json.load(_f)

RECORDS: dict[str, dict] = G["records"]
FIELDS = ("status", "item", "category", "detail")
BROWSER_ONLY = {"v02", "v04", "v21"}


def _inputs(case: dict) -> tuple[str, str]:
    if "input_ref" in case:
        with (REPO / case["input_ref"]).open(encoding="utf-8") as f:
            page = json.load(f)
        return page["html"], page["css"]
    return case["html"], case["css"]


def _expected(key: str) -> dict:
    cid, status, _ = key.split(":")
    return {"id": cid, "status": status, **RECORDS[key]}


def _diff_run(case: dict, run: dict) -> list[str]:
    """Every way the Python engine's run differs from the TypeScript one."""
    html, css = _inputs(case)
    effective, raw_tokens, checks = mcp._offline_checks(html, css, run["subject"], run["scope"])
    problems = []
    if effective != run["effective_scope"]:
        problems.append(f"effective scope: python={effective!r} ts={run['effective_scope']!r}")
    if len(raw_tokens) != run["tokens_extracted"]:
        problems.append(f"tokens_extracted: python={len(raw_tokens)} ts={run['tokens_extracted']}")
    by_id = {c["id"]: c for c in checks}
    for key in run["checks"]:
        want = _expected(key)
        got = by_id.get(want["id"])
        if got is None:
            continue  # not ported: covered by test_every_live_check_is_ported_or_listed
        for field in FIELDS:
            if got[field] != want[field]:
                problems.append(f"{want['id']}.{field}: python={got[field]!r} ts={want[field]!r}")
    return problems


RUNS = [(case, i, run) for case in G["case_detail"] for i, run in enumerate(case["runs"])]


def _run_id(item) -> str:
    case, i, run = item
    return f"{case['name']}[{run['scope'] or 'auto'}#{i}]"


# ── The golden itself ─────────────────────────────────────────────────────────


class TestGolden:
    def test_is_generated_from_the_typescript_engine(self):
        assert "GENERATED by packages/score/scripts/export-offline-golden.mjs" in G["$comment"]
        assert G["cases"] == len(G["case_detail"])
        assert G["runs"] == len(RUNS)
        assert len(G["check_ids"]) == len(set(G["check_ids"])) == 45

    def test_every_run_lists_every_live_check_once_in_order(self):
        for case, _, run in RUNS:
            assert [k.split(":")[0] for k in run["checks"]] == G["check_ids"], case["name"]
            assert all(k in RECORDS for k in run["checks"]), case["name"]

    def test_parity_page_input_is_the_one_the_golden_was_made_from(self):
        # The page is read from packages/score rather than copied into the
        # golden, so a re-recorded page must come with a regenerated golden.
        (case,) = [c for c in G["case_detail"] if "input_ref" in c]
        html, css = _inputs(case)
        digest = hashlib.sha256((html + "\u0000" + css).encode("utf-8")).hexdigest()
        assert digest == case["input_sha256"]

    def test_covers_each_engine_1_1_0_change_in_both_directions(self):
        seen = defaultdict(set)
        for _, _, run in RUNS:
            for key in run["checks"]:
                rec = _expected(key)
                seen[(rec["id"], run["effective_scope"])].add((rec["status"], rec["detail"]))
        v05 = seen[("v05", "contract")] | seen[("v05", "universal")]
        assert any(s == "PASS" and d.startswith("motion is opt-in") for s, d in v05)
        assert any(s == "WARN" and "gates no motion" in d for s, d in v05)
        v27 = seen[("v27", "contract")] | seen[("v27", "universal")]
        assert {"SKIP", "WARN", "PASS", "FAIL"} <= {s for s, _ in v27}
        for cid in ("v14", "v18"):
            assert any(s == "SKIP" and "scope=universal" in d for s, d in seen[(cid, "universal")]), cid
            assert any(s == "WARN" for s, _ in seen[(cid, "contract")]), cid

    def test_reaches_more_than_one_verdict_for_every_ported_check(self):
        # A check the golden only ever sees in one state is compared, but not
        # tested: a port that hard-coded that state would pass. Only the three
        # browser-only checks are constant by design.
        statuses = defaultdict(set)
        for _, _, run in RUNS:
            for key in run["checks"]:
                cid, status, _ = key.split(":")
                statuses[cid].add(status)
        thin = [cid for cid in mcp.OFFLINE_CHECK_IDS if cid not in BROWSER_ONLY and len(statuses[cid]) < 2]
        assert thin == [], f"golden never moves these checks off one verdict: {thin}"
        assert all(statuses[cid] == {"MANUAL"} for cid in BROWSER_ONLY)


# ── Coverage: ported or listed, nothing silent ──────────────────────────────────


class TestCoverage:
    def test_every_live_check_is_ported_or_listed(self):
        live = G["check_ids"]
        ported = set(mcp.OFFLINE_CHECK_IDS)
        listed = set(mcp._OFFLINE_NOT_IMPLEMENTED)
        assert ported.isdisjoint(listed), sorted(ported & listed)
        assert ported | listed == set(live), {
            "in the live engine, neither ported nor listed": sorted(set(live) - ported - listed),
            "ported or listed, not in the live engine": sorted((ported | listed) - set(live)),
        }

    def test_ported_checks_keep_the_live_order(self):
        assert list(mcp.OFFLINE_CHECK_IDS) == [c for c in G["check_ids"] if c in set(mcp.OFFLINE_CHECK_IDS)]
        assert list(mcp._OFFLINE_NOT_IMPLEMENTED) == [c for c in G["check_ids"] if c in mcp._OFFLINE_NOT_IMPLEMENTED]

    def test_every_listed_check_carries_a_reason(self):
        for cid, reason in mcp._OFFLINE_NOT_IMPLEMENTED.items():
            assert len(reason) > 40, cid

    def test_the_engine_runs_exactly_the_ported_checks(self):
        _, _, checks = mcp._offline_checks("<html></html>", "")
        assert [c["id"] for c in checks] == list(mcp.OFFLINE_CHECK_IDS)

    def test_mirrored_versions_match_the_live_engine(self):
        assert mcp.OFFLINE_ENGINE_MIRRORS == G["engine_version"]
        assert mcp.OFFLINE_CONTRACT_VERSION == G["contract_version"]
        # Also against the live constant directly, so a version bump fails here
        # even before anyone regenerates the golden.
        src = (REPO / "apps/site/app/lib/check-definitions.ts").read_text(encoding="utf-8")
        live = re.search(r"export const ENGINE_VERSION = '(\d+\.\d+\.\d+)';", src).group(1)
        assert mcp.OFFLINE_ENGINE_MIRRORS == live

    def test_the_published_counts_are_the_engines(self):
        ported = len(mcp.OFFLINE_CHECK_IDS)
        total = ported + len(mcp._OFFLINE_NOT_IMPLEMENTED)
        phrase = f"{ported} of the {total} checks"
        assert phrase in mcp.TOOL_MAP["designesy_score"]["description"]
        assert phrase in (HERE.parent / "README.md").read_text(encoding="utf-8")


# ── Parity, run by run ─────────────────────────────────────────────────────────


@pytest.mark.parametrize("item", RUNS, ids=[_run_id(r) for r in RUNS])
def test_parity(item):
    case, _, run = item
    problems = _diff_run(case, run)
    assert problems == [], f"{case['name']} scope={run['scope']} subject={run['subject']}:\n  " + "\n  ".join(problems)


def test_the_comparison_catches_a_reverted_engine_1_1_0_change():
    # Negative control. If the comparison had no teeth (a wrong field, an
    # empty golden, a skipped branch), reverting a 1.1.0 change would still
    # pass. Each revert below must produce mismatches on the check it touches.
    def mismatched_ids() -> Counter:
        ids = Counter()
        for case, _, run in RUNS:
            for p in _diff_run(case, run):
                ids[p.split(".")[0]] += 1
        return ids

    with patch.object(mcp, "_opts_into_motion", lambda body: False):
        assert set(mismatched_ids()) == {"v05"}
    with patch.object(mcp, "_has_zoomable_field", lambda html: True):
        assert set(mismatched_ids()) == {"v27"}
    tier1 = [t for t in mcp._TIER2_ABSENCE_PATTERNS if t[0] not in ("v14", "v18")]
    with patch.object(mcp, "_TIER2_ABSENCE_PATTERNS", tier1):
        assert set(mismatched_ids()) == {"v14", "v18"}


