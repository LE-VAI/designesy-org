#!/usr/bin/env node
// scripts/rescore-leaderboard.mjs
//
// Re-scores every leaderboard seed site against the live designesy.org
// /api/score engine, computes delta-since-last-week badges, and regenerates
// the seed.ts + snapshot.json files.
//
// Run by .github/workflows/rescore-leaderboard.yml every Monday 10:00 UTC.
// Can also be run locally: node scripts/rescore-leaderboard.mjs
//
// Output:
//   apps/site/app/leaderboard/seed.ts      — updated with new scores + prevScore
//   apps/site/app/leaderboard/snapshot.json — this week's scores (for next week's delta)
//   apps/site/app/leaderboard/batch-data.ts — each site's per-category breakdown
//   apps/site/app/docs/self-report.json     — the site's own receipt on /docs
//
// --categories-only: re-score and rewrite batch-data.ts alone, leaving the
// composites (seed.ts, snapshot.json) and the receipt to the weekly run.
//
// The script reads the current seed.ts to extract the site list and the
// previous scores (prevScore), then writes the new scores as the current
// score and moves the old current score to prevScore.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SEED_PATH = join(ROOT, 'apps/site/app/leaderboard/seed.ts');
const SNAPSHOT_PATH = join(ROOT, 'apps/site/app/leaderboard/snapshot.json');
const BATCH_PATH = join(ROOT, 'apps/site/app/leaderboard/batch-data.ts');
const SCORE_API = process.env.SCORE_API || 'https://www.designesy.org/api/score';
const CATEGORIES_ONLY = process.argv.includes('--categories-only');

// Last-resort check count, used only if the engine reply omits `total`. The
// engine's own number is preferred so the seed header cannot drift from the
// engine it describes; this value is a fallback, not the source of truth.
const ENGINE_CHECK_COUNT_FALLBACK = 44;

// ── The per-category batch (batch-data.ts) ──────────────────────────────────
//
// The data pages draw each site's category breakdown beside its composite.
// That breakdown came from a one-off script (apps/site/batch-run.mjs, now gone) and went
// stale: two months behind the weekly composites, with the semantic category
// still unscored everywhere although the engine had scored it since
// 2026-08-30. The weekly run already receives every site's categoryScores, so
// it now writes them too, onto the same 11-key ring the leaderboard draws. A
// site the engine could not read keeps its previous breakdown, exactly as its
// composite keeps its previous score (the unreachable guard below).
const RING = ['cadence', 'accessibility', 'semantic', 'motion', 'tokens', 'takt', 'poise', 'identity', 'interaction', 'performance', 'responsive'];
const RING_WEIGHTS = { cadence: 18, accessibility: 15, semantic: 12, motion: 10, tokens: 9, takt: 8, poise: 7, identity: 6, interaction: 6, performance: 6, responsive: 3 };

function ringOf(categoryScores) {
  const out = {};
  for (const k of RING) {
    const v = categoryScores ? categoryScores[k] : null;
    const weight = v && typeof v.weight === 'number' ? v.weight : RING_WEIGHTS[k];
    out[k] = v && v.score !== null && v.score !== undefined
      ? { score: Math.round(v.score * 10) / 10, weight, pass: v.pass | 0, fail: v.fail | 0, warn: v.warn | 0, skip: v.skip | 0 }
      : { score: null, weight, pass: 0, fail: 0, warn: 0, skip: 0 };
  }
  return out;
}

/** The previous run's breakdowns, verbatim text per URL, to carry forward. */
function previousBatchBlocks() {
  if (!existsSync(BATCH_PATH)) return {};
  const src = readFileSync(BATCH_PATH, 'utf-8').replace(/\r\n/g, '\n');
  const blocks = {};
  for (const m of src.matchAll(/^  "(https?:\/\/[^"]+)": \{\n([\s\S]*?)\n  \},$/gm)) blocks[m[1]] = m[2];
  return blocks;
}

function generateBatchTS(entries, runDate) {
  const prev = previousBatchBlocks();
  const blocks = [];
  let carried = 0;
  for (const e of entries) {
    let inner;
    if (e.categoryScores) {
      const ring = ringOf(e.categoryScores);
      inner = RING.map((k) => {
        const c = ring[k];
        return `    "${k}": { score: ${c.score === null ? 'null' : c.score}, weight: ${c.weight}, pass: ${c.pass}, fail: ${c.fail}, warn: ${c.warn}, skip: ${c.skip} },`;
      }).join('\n');
    } else if (prev[e.url]) {
      inner = prev[e.url];
      carried++;
    } else {
      continue;
    }
    blocks.push(`  "${e.url}": {\n${inner}\n  },`);
  }
  const header = [
    '// Real per-category fingerprints for the leaderboard mini-constellation ring.',
    '//',
    '// GENERATED by scripts/rescore-leaderboard.mjs, the weekly re-score, against',
    '// the live /api/score engine: never hand-author numbers here. Each entry is',
    '// the categoryScores map the engine returned for that URL, mapped onto the',
    '// full 11-key ring (missing categories -> score:null = unscored dashed node).',
    '// A site the engine could not read keeps its previous entry.',
    '',
    "import type { CategoryBreakdown } from './seed';",
    '',
    '/** The day the batch below was run: the date every per-category figure on the',
    '    data pages carries, beside the composite\'s weekly re-score date. */',
    `export const BATCH_RUN_DATE = '${runDate}';`,
    '',
    'export const BATCH_CATEGORY_SCORES: Record<string, Record<string, CategoryBreakdown>> = {',
  ].join('\n');
  return { text: `${header}\n${blocks.join('\n')}\n};\n`, carried, written: blocks.length };
}

// ── Extract the RAW_SEED array from seed.ts ──────────────────────────────
// We parse the TypeScript source text to extract the seed entries rather than
// importing the module (which would require a TS compiler). The RAW_SEED is
// a flat array of object literals — we regex-extract each entry's URL, name,
// tier, category, score, grade, pass, fail, warn, skip, tokens, seededBecause.

function extractSeedEntries(src) {
  // Find the RAW_SEED array bounds
  const arrayStart = src.indexOf('const RAW_SEED');
  if (arrayStart === -1) throw new Error('Could not find RAW_SEED in seed.ts');
  const arrayEnd = src.indexOf('];', arrayStart);
  const arrayText = src.slice(arrayStart, arrayEnd + 2);

  // Extract each object literal in the array
  const entries = [];
  const objRegex = /\{[^{}]*\burl:[^{}]*\}/gs;
  const matches = arrayText.match(objRegex) || [];

  for (const m of matches) {
    // A quoted value is read whole, commas and escaped quotes included; a bare
    // value (number, null) runs to the next comma or brace. The old single
    // pattern stopped every string at its first comma.
    const extract = (key) => {
      const r = new RegExp(`\\b${key}:\\s*('(?:[^'\\\\]|\\\\.)*'|"(?:[^"\\\\]|\\\\.)*"|[^,}]+)`);
      const match = m.match(r);
      if (!match) return null;
      const val = match[1].trim();
      if (val.startsWith("'") || val.startsWith('"')) return val.slice(1, -1).replace(/\\(.)/g, '$1');
      return val;
    };

    const url = extract('url');
    const name = extract('name');
    const tier = parseInt(extract('tier') || '0', 10);
    const category = extract('category');
    const score = parseFloat(extract('score') || 'null');
    const grade = extract('grade');
    const pass = parseInt(extract('pass') || '0', 10);
    const fail = parseInt(extract('fail') || '0', 10);
    const warn = parseInt(extract('warn') || '0', 10);
    const skip = parseInt(extract('skip') || '0', 10);
    const tokens = parseInt(extract('tokens') || '0', 10);
    const seededBecause = extract('seededBecause');

    if (url) {
      entries.push({ url, name, tier, category, score: isNaN(score) ? null : score, grade, pass, fail, warn, skip, tokens, seededBecause, prevScore: null });
    }
  }
  return entries;
}

// ── Load the previous snapshot for delta computation ────────────────────
function loadPrevSnapshot() {
  if (!existsSync(SNAPSHOT_PATH)) return {};
  try {
    return JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf-8'));
  } catch {
    return {};
  }
}

// ── Fetch a live score from the engine ───────────────────────────────────
async function fetchScore(url) {
  const res = await fetch(SCORE_API, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ url }),
  });
  if (!res.ok) {
    throw new Error(`HTTP ${res.status}: ${await res.text().catch(() => res.statusText)}`);
  }
  const data = await res.json();
  return {
    score: data.score ?? null,
    grade: data.grade ?? null,
    pass: data.pass ?? 0,
    fail: data.fail ?? 0,
    warn: data.warn ?? 0,
    skip: data.skip ?? 0,
    tokens: data.tokensExtracted ?? 0,
    categoryScores: data.categoryScores ?? null,
    // The contract version the engine scored against, captured so the seed's
    // LEADERBOARD_VERSION can be kept in step instead of hand-maintained.
    // Dropping this field is why that constant sat at 0.4.0 while the engine
    // served v0.4.1: the API had it all along and nobody read it.
    contractVersion: data.contractVersion ?? null,
    // The engine's own check count, so the seed header describes the engine that
    // actually ran rather than a number pinned in this script.
    totalChecks: data.total ?? null,
    // The engine version from the engine's receipt, so the pages can name the
    // engine that produced these scores rather than the repo's current one.
    engineVersion: data.receipt?.engine_version ?? null,
  };
}

// ── Generate the updated seed.ts ─────────────────────────────────────────
//
// SURGICAL REWRITE — the 2026-08-30 run proved the previous full-file
// regeneration approach wrong: it rebuilt seed.ts from a hardcoded template
// that predates fields added since the last successful run (liveScoreUrl,
// coiDisclosure), stripping them and breaking page.tsx's typecheck
// (TS2339). The template also held a stale LEADERBOARD_VERSION.
//
// Instead: keep the file as-is and rewrite ONLY the fields this script
// owns — per-entry score fields + prevScore, the header comment's re-score
// date, LEADERBOARD_LAST_SCORED, and the count in LEADERBOARD_POLICY.
// Unknown present or FUTURE fields pass through untouched, so schema
// additions no longer break the weekly re-score.
function generateSeedTS(src, entries, lastScored, contractVersion, totalChecks, engineVersion) {
  let out = src;

  // 1. Header comment: "All N sites re-scored DATE with the N-check engine
  //    (contract vX.Y.Z)."
  //
  // The engine-check count and the contract version are captured rather than
  // hardcoded. The previous pattern pinned the literal words "40-check engine",
  // so when the site moved to 42 checks the regex stopped matching and the
  // header date froze at 2026-08-30 for weeks — silently, because a `.replace`
  // that matches nothing returns the input unchanged and throws nothing. A
  // date field this script claims to own must not be able to stop updating
  // without saying so.
  const headerRe = /(\/\/ All \d+ sites re-scored )\d{4}-\d{2}-\d{2}( with the )\d+(?:-\d+)?(-check engine \(contract v)[\d.]+(\))/;
  if (!headerRe.test(out)) {
    throw new Error(
      'generateSeedTS: seed.ts header comment did not match the expected shape ' +
      '"// All N sites re-scored DATE with the N-check engine (contract vX.Y.Z)." ' +
      'Refusing to continue, because the alternative is a field that silently stops updating.'
    );
  }
  const checkCount = totalChecks ?? ENGINE_CHECK_COUNT_FALLBACK;
  // The header's "contract v" already carries the v, so strip any leading v from
  // the engine's own version string before interpolating it. Without this the
  // header renders "contract vv0.4.1".
  const headerVersion = contractVersion ? String(contractVersion).replace(/^v/, '') : 'unknown';
  out = out.replace(
    headerRe,
    (_, p1, p2, p3, p4) => `${p1}${lastScored}${p2}${checkCount}${p3}${headerVersion}${p4}`
  );

  // 1b. LEADERBOARD_VERSION — the contract version these scores were computed
  //     against. Derived from the engine's own reply, never hand-authored.
  if (contractVersion) {
    const bare = String(contractVersion).replace(/^v/, '');
    const verRe = /(export const LEADERBOARD_VERSION = ')[\d.]+(';)/;
    if (!verRe.test(out)) {
      throw new Error('generateSeedTS: LEADERBOARD_VERSION declaration not found in seed.ts');
    }
    out = out.replace(verRe, `$1${bare}$2`);
  }

  // 1c. LEADERBOARD_ENGINE_VERSION: the engine that produced these scores,
  //     from its own receipt. Kept as-is when no reply carried one.
  if (engineVersion) {
    const engRe = /(export const LEADERBOARD_ENGINE_VERSION = ')[^']+(';)/;
    if (!engRe.test(out)) {
      throw new Error('generateSeedTS: LEADERBOARD_ENGINE_VERSION declaration not found in seed.ts');
    }
    out = out.replace(engRe, `$1${engineVersion}$2`);
  }

  // 2. Each entry: rewrite the fields we own inside its object literal.
  //    Match each RAW_SEED entry by its url: '...' anchor, then swap the
  //    owned scalar fields inside that literal only.
  for (const e of entries) {
    const anchor = e.url.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    // Locate the entry's object literal via its unique url anchor.
    const entryRegex = new RegExp(`(\\{[^{}]*url: '${anchor}'[^{}]*\\})`);
    const m = out.match(entryRegex);
    if (!m) {
      throw new Error(`generateSeedTS: could not locate entry for ${e.url} in seed.ts`);
    }
    let entryText = m[1];

    const swap = (key, value) => {
      const re = new RegExp(`${key}:\\s*('[^']*'|null|\\d+(?:\\.\\d+)?)`);
      if (re.test(entryText)) {
        entryText = entryText.replace(re, `${key}: ${value}`);
        return true;
      }
      return false;
    };

    const num = (v) => (v === null || v === undefined ? 'null' : String(v));
    const swapRequired = (key, value) => {
      if (!swap(key, value)) {
        throw new Error(`generateSeedTS: field ${key} missing on entry ${e.url} — seed schema and script disagree`);
      }
    };

    swapRequired('score', num(e.score));
    swapRequired('grade', e.grade ? `'${e.grade}'` : 'null');
    swapRequired('pass', num(e.pass));
    swapRequired('fail', num(e.fail));
    swapRequired('warn', num(e.warn));
    swapRequired('skip', num(e.skip));
    swapRequired('tokens', num(e.tokens));
    // prevScore is optional in the schema (older entries lack it) — swap when
    // present, skip silently when absent rather than failing the whole run.
    swap('prevScore', num(e.prevScore));

    // scoredAt / unreachable: UPDATE IF PRESENT, INJECT IF ABSENT.
    //
    // These were originally injected unconditionally, on the stated premise that
    // they are "new fields that no existing seed row contains". That premise
    // EXPIRED: the UNREACHABLE guard (earlier work) added `scoredAt` to all 30
    // rows on main, so this injector began appending a SECOND `scoredAt` to every
    // row. That is a TypeScript error — TS1117 "An object literal cannot have
    // multiple properties with the same name" — on ~17 rows, and it has been
    // silently breaking the automated weekly re-score.
    //
    // Symptom to recognise if it recurs: the weekly leaderboard PR fails
    // `Build site` with a wall of TS1117 on seed.ts.
    //
    // Idempotent now, because a generator that only works on the first run is
    // not a generator, it is a one-shot script wearing a cron entry.
    const scoredAtValue = e.scoredAt || lastScored;
    const scoredAtRe = /,?\s*scoredAt:\s*'[^']*'/;
    if (scoredAtRe.test(entryText)) {
      entryText = entryText.replace(scoredAtRe, `, scoredAt: '${scoredAtValue}'`);
    } else {
      entryText = entryText.replace(
        /\s*\}\s*$/,
        `, scoredAt: '${scoredAtValue}' }`,
      );
    }

    // unreachable follows the same rule for the same reason.
    const unreachableRe = /,?\s*unreachable:\s*(?:true|false)/;
    if (e.unreachable === true) {
      if (unreachableRe.test(entryText)) {
        entryText = entryText.replace(unreachableRe, ', unreachable: true');
      } else {
        entryText = entryText.replace(/\s*\}\s*$/, ', unreachable: true }');
      }
    } else if (unreachableRe.test(entryText)) {
      // was unreachable, now measured — drop the stale flag rather than keep it.
      entryText = entryText.replace(unreachableRe, '');
    }

    out = out.replace(m[0], entryText);
  }

  // 3. LEADERBOARD_LAST_SCORED = '...'
  out = out.replace(
    /(LEADERBOARD_LAST_SCORED = ')\d{4}-\d{2}-\d{2}(')/,
    `$1${lastScored}$2`
  );

  // 4. LEADERBOARD_POLICY count: "Curated seed (N sites)"
  out = out.replace(
    /(Curated seed \()\d+( sites)/,
    `$1${entries.length}$2`
  );

  return out;
}

// ── Main ─────────────────────────────────────────────────────────────────
async function main() {
  console.log('Reading current seed.ts...');
  const src = readFileSync(SEED_PATH, 'utf-8');
  const entries = extractSeedEntries(src);
  console.log(`Found ${entries.length} seed sites.`);

  // Load previous snapshot for delta computation
  const prevSnapshot = loadPrevSnapshot();
  const prevCount = Object.keys(prevSnapshot).length;
  console.log(`Loaded previous snapshot (${prevCount} entries).`);

  // Set prevScore from the snapshot (the previous week's scores)
  for (const entry of entries) {
    if (prevSnapshot[entry.url] && prevSnapshot[entry.url].score !== null) {
      entry.prevScore = prevSnapshot[entry.url].score;
    }
  }

  // The run date, resolved ONCE and used by both the scoring loop (to stamp
  // entry.scoredAt) and the seed generator. It must be defined before the loop:
  // an earlier version declared it after, which would have thrown.
  const now = new Date();
  const lastScored = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;

  // Re-score every site
  console.log(`Scoring ${entries.length} sites against ${SCORE_API}...`);
  let success = 0;
  let errors = 0;
  /** URLs the engine could not read — reported at the end, never republished. */
  const unreachable = [];

  // Captured from the engine's own reply during the run, then written into the
  // seed so LEADERBOARD_VERSION and the header's check count describe the engine
  // that actually produced these numbers rather than being hand-maintained.
  let runContractVersion = null;
  let runTotalChecks = null;
  let runEngineVersion = null;

  for (let i = 0; i < entries.length; i++) {
    const entry = entries[i];
    try {
      console.log(`  [${i + 1}/${entries.length}] ${entry.url} ...`);
      const result = await fetchScore(entry.url);

      // ── UNREACHABLE GUARD ──────────────────────────────────────────────
      // The engine returns score:null for a target it could not read (403,
      // redirect loop, timeout). That must NOT overwrite a previously-measured
      // grade: doing so would replace a real reading with a statement about our
      // own fetch, and republish it as if it were a measurement.
      //
      // This is the exact failure that produced the 2026-09-18 run: nytimes.com
      // (74.7 C) and getdesy.com (73.4 C) both returned 403 and were about to be
      // republished as 61.5 D — the score of the placeholder document the engine
      // used to grade instead of reporting the failure.
      if (result.score === null) {
        unreachable.push(entry.url);
        entry.unreachable = true;
        // Carry the PREVIOUS measurement date forward. Stamping today would
        // claim a measurement that did not happen.
        entry.scoredAt = (prevSnapshot[entry.url] && prevSnapshot[entry.url].scoredAt) || null;
        // Keep the stored score and grade untouched; record why it is stale.
        console.log(`    → UNREACHABLE (no score reported) — keeping stored ${entry.score} ${entry.grade}`);
        continue;
      }

      entry.unreachable = false;
      entry.scoredAt = lastScored;
      entry.categoryScores = result.categoryScores;
      entry.score = result.score;
      entry.grade = result.grade;
      entry.pass = result.pass;
      entry.fail = result.fail;
      entry.warn = result.warn;
      entry.skip = result.skip;
      entry.tokens = result.tokens;
      success++;

      // Record the contract version and engine check count this run was scored
      // against, taken from the engine's own reply. Captured on the first
      // successful score; every site in a run is scored by the same engine.
      if (runContractVersion === null && result.contractVersion) {
        runContractVersion = result.contractVersion;
      }
      if (runEngineVersion === null && result.engineVersion) {
        runEngineVersion = result.engineVersion;
      }
      if (runTotalChecks === null && result.totalChecks) {
        runTotalChecks = result.totalChecks;
      }

      const delta = entry.prevScore !== null && entry.score !== null
        ? ` (prev ${entry.prevScore}, Δ${(entry.score - entry.prevScore).toFixed(1)})`
        : '';
      console.log(`    → ${result.score} ${result.grade}${delta}`);
    } catch (e) {
      errors++;
      console.log(`    → ERROR: ${e.message}`);
      // Keep the existing score on error
    }

    // Be polite to the API (the 24h cache means most hits are instant,
    // but cold scores take 3-8s — this delay prevents burst rate-limiting)
    await new Promise((r) => setTimeout(r, 500));
  }

  console.log(`\nRe-score complete: ${success} scored, ${errors} errors.`);

  if (unreachable.length > 0) {
    // Printed loudly: an unreachable site keeps its previous grade, so the
    // operator must know these rows are stale rather than assuming the whole
    // cohort was refreshed.
    console.log('');
    console.log('UNREACHABLE - stored grade kept, NOT re-measured this run:');
    for (const u of unreachable) console.log('  - ' + u);
    console.log('');
    console.log('These rows are stale by design: republishing them with a score derived');
    console.log('from an unread page would replace a measurement with a fetch failure.');
  }

  // The per-category batch, from this same run.
  const batch = generateBatchTS(entries, lastScored);
  writeFileSync(BATCH_PATH, batch.text, 'utf-8');
  console.log(`Writing batch-data.ts (${batch.written} sites, ${batch.carried} carried forward)...`);
  if (CATEGORIES_ONLY) {
    console.log('\n--categories-only: seed.ts, snapshot.json and the receipt left as they were.');
    return;
  }

  // Write the updated seed.ts
  console.log(`Writing updated seed.ts (last scored ${lastScored})...`);
  console.log(`  engine reported: engine ${runEngineVersion ?? 'unknown'}, contract ${runContractVersion ?? 'unknown'}, ${runTotalChecks ?? '?'} checks`);
  const newSeedTS = generateSeedTS(src, entries, lastScored, runContractVersion, runTotalChecks, runEngineVersion);
  writeFileSync(SEED_PATH, newSeedTS, 'utf-8');

  // Write this week's snapshot (for next week's delta)
  const snapshot = {};
  for (const entry of entries) {
    // PRESERVE scoredAt for unreachable entries.
    //
    // The guard above keeps a stored score when the engine cannot read a site,
    // but this loop previously stamped `scoredAt` on EVERY entry regardless —
    // so an unmeasured row claimed to have been measured today. That is the same
    // defect the guard exists to prevent, one layer down: a score whose
    // provenance asserts something that did not happen.
    //
    // The prior timestamp is carried forward from the existing snapshot so the
    // date always names the run that actually produced the number.
    const prior = prevSnapshot[entry.url];
    const wasUnmeasured = entry.unreachable === true;
    snapshot[entry.url] = {
      score: entry.score,
      grade: entry.grade,
      pass: entry.pass,
      fail: entry.fail,
      warn: entry.warn,
      skip: entry.skip,
      tokens: entry.tokens,
      scoredAt: wasUnmeasured && prior && prior.scoredAt ? prior.scoredAt : lastScored,
      ...(wasUnmeasured ? { unreachable: true } : {}),
    };
  }
  console.log('Writing snapshot.json...');
  writeFileSync(SNAPSHOT_PATH, JSON.stringify(snapshot, null, 2) + '\n', 'utf-8');

  // ── Self-report receipt ────────────────────────────────────────────────
  //
  // /docs publishes a "Drift score acknowledged" section — the site's own
  // receipt, on a site whose entire thesis is receipts. Those figures were
  // literal strings in app/docs/page.tsx, so they went stale the moment any
  // engine changed. Found 2026-09-23: it claimed drift 92/A and readiness
  // 80/B with an A(91) composite, while the live engines returned drift
  // 96/A and readiness 90/A — the page was under-selling the site by two
  // grade bands' worth of confidence, and the whole point of that section is
  // that the number is checkable.
  //
  // Hand-editing is provably a losing game: the figures moved twice in one
  // session. So the receipt is now DERIVED. This script runs weekly, so it
  // is the natural producer: it already talks to /api/score and already has
  // the self row. It now also records the two engines /docs quotes, the
  // composite (by the site's own published formula), and each engine's
  // pass/warn/fail counts — into a committed JSON that page.tsx imports.
  //
  // If a fetch fails the file is left untouched rather than written with
  // nulls: a receipt that says "0" because a request timed out is worse than
  // a receipt that is one week old.
  try {
    const SELF_URL = 'https://www.designesy.org';
    const selfEntry = entries.find((e) => e.url === SELF_URL || e.url === SELF_URL + '/');
    if (selfEntry && selfEntry.score !== null) {
      const engines = {
        score: {
          score: selfEntry.score,
          grade: selfEntry.grade,
          pass: selfEntry.pass, warn: selfEntry.warn, fail: selfEntry.fail, skip: selfEntry.skip,
          checks: selfEntry.pass + selfEntry.warn + selfEntry.fail + selfEntry.skip,
        },
      };
      for (const [key, path] of [['drift', '/api/drift'], ['readiness', '/api/readiness']]) {
        try {
          const r = await fetch(new URL(path, SCORE_API).toString(), {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ url: SELF_URL }),
          });
          if (r.ok) {
            const d = await r.json();
            engines[key] = {
              score: d.score, grade: d.grade,
              pass: d.pass, warn: d.warn, fail: d.fail,
              checks: d.checks ? d.checks.length : null,
              // /docs cites the :root token count in prose; carry it here so
              // the receipt never has to hardcode a number again.
              ...(typeof d.tokensExtracted === 'number' ? { tokenCount: d.tokensExtracted } : {}),
              // The per-check list lets /docs name the exact WARN/FAIL entries
              // instead of paraphrasing them — the paraphrase is what went
              // stale last time.
              notes: (d.checks || [])
                .filter((c) => c.status !== 'PASS')
                .map((c) => ({ id: c.id, status: c.status, detail: c.detail })),
            };
          }
        } catch (err) {
          console.log(`  (self-report: ${key} fetch failed — leaving prior value in place)`);
        }
      }
      const dr = engines.drift?.score, rd = engines.readiness?.score;
      const selfReport = {
        generatedAt: lastScored,
        formula: 'score * 0.5 + drift * 0.3 + readiness * 0.2',
        engines,
        ...(typeof dr === 'number' && typeof rd === 'number'
          ? { composite: Math.round((engines.score.score * 0.5 + dr * 0.3 + rd * 0.2) * 10) / 10 }
          : {}),
      };
      const OUT = join(ROOT, 'apps/site/app/docs/self-report.json');
      writeFileSync(OUT, JSON.stringify(selfReport, null, 2) + '\n', 'utf-8');
      console.log(`Writing self-report.json (composite ${selfReport.composite ?? 'incomplete'})...`);
    }
  } catch (err) {
    console.log(`  (self-report: skipped — ${err.message})`);
  }

  // Summary
  const deltas = entries
    .filter((e) => e.prevScore !== null && e.score !== null)
    .map((e) => ({ name: e.name, delta: e.score - e.prevScore }))
    .filter((d) => d.delta !== 0);

  console.log(`\nDelta summary: ${deltas.length} site(s) changed score since last week.`);
  for (const d of deltas) {
    const arrow = d.delta > 0 ? '↑' : '↓';
    console.log(`  ${arrow} ${d.name}: ${d.delta > 0 ? '+' : ''}${d.delta.toFixed(1)}`);
  }
  if (deltas.length === 0) {
    console.log('  (no changes — all sites scored the same as last week)');
  }

  console.log('\nDone. Commit the updated files to deploy.');
}

main().catch((e) => {
  console.error('FATAL:', e);
  process.exit(1);
});